CREATE TABLE IF NOT EXISTS mtl_employer (
    employer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_name VARCHAR(255),
    employer_code VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS mtl_member (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(150),
    middle_name VARCHAR(150),
    last_name VARCHAR(150),
    ssn VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS mtl_payment_type (
    payment_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type_code VARCHAR(100),
    source VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS mtl_ar_payment_status (
    payment_status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_status_code VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS mtl_ar_payment_sub_status (
    payment_sub_status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_sub_status_code VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS mtl_bank_account_info (
    bank_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_account_name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS mtl_ar_deposit_bundle (
    deposit_bundle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deposit_bundle_number VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS mtl_ar_payment_entry (
    payment_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    deposit_bundle_id BIGINT REFERENCES mtl_ar_deposit_bundle(deposit_bundle_id),
    customer_id BIGINT NOT NULL,
    employer_id BIGINT REFERENCES mtl_employer(employer_id),
    member_id BIGINT REFERENCES mtl_member(member_id),
    bank_account_id BIGINT REFERENCES mtl_bank_account_info(bank_account_id),
    payment_type_id BIGINT REFERENCES mtl_payment_type(payment_type_id),
    payment_reference_no VARCHAR(255),
    amount_received NUMERIC(19, 2),
    received_date DATE,
    postmark_date DATE,
    deposited_date DATE,
    payment_status_id BIGINT REFERENCES mtl_ar_payment_status(payment_status_id),
    payment_sub_status_id BIGINT REFERENCES mtl_ar_payment_sub_status(payment_sub_status_id),
    accounting_month VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    employer_notes VARCHAR(500),
    remarks TEXT,
    fd_amount NUMERIC(19, 2),
    payment_id VARCHAR(100),
    balance_amount NUMERIC(19, 2) NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_payment_entry_tenant_customer_month
    ON mtl_ar_payment_entry (tenant_id, customer_id, accounting_month);
CREATE INDEX IF NOT EXISTS idx_payment_entry_deposited_date
    ON mtl_ar_payment_entry (deposited_date);
